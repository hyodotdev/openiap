#!/bin/bash

# Write the Client Protocol version into openiap-versions.json, then sync that
# manifest out to packages. Symlinks for native packages, copies for docs
# (Vercel requirement).

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"

cd "$REPO_ROOT"

# specs/client publishes the Client Protocol, so its manifest is the source and
# openiap-versions.json is a generated mirror. Propagate before anything reads
# the manifest; the audits gate the committed state.
python3 - <<'PROPAGATE'
import json
from pathlib import Path

manifest = Path("openiap-versions.json")
versions = json.loads(manifest.read_text(encoding="utf-8"))
published = json.loads(
    Path("specs/client/package.json").read_text(encoding="utf-8")
)["version"]
if versions.get("clientProtocol") != published:
    versions["clientProtocol"] = published
    manifest.write_text(json.dumps(versions, indent=2) + "\n", encoding="utf-8")
    print(f"  ✓ openiap-versions.json clientProtocol -> {published}")
PROPAGATE

echo "📦 Syncing version files..."

sync_package_json_version() {
    local package_path="$1"
    local version_key="$2"

    if [ ! -f "$package_path" ]; then
        echo "  ! Skipping $package_path (missing)"
        return
    fi

    python3 - "$package_path" "$version_key" <<'PY'
import json
import sys
from pathlib import Path

package_path, version_key = sys.argv[1:]
versions = json.loads(Path("openiap-versions.json").read_text(encoding="utf-8"))
version = versions.get(version_key)
if not isinstance(version, str) or not version:
    raise SystemExit(f"openiap-versions.json missing {version_key} version")

path = Path(package_path)
package = json.loads(path.read_text(encoding="utf-8"))
package["version"] = version
path.write_text(json.dumps(package, indent=2) + "\n", encoding="utf-8")
PY
    echo "  ✓ $package_path -> $version_key"
}

echo ""
echo "📦 Syncing package metadata..."
# packages/docs is not versioned; its version stays pinned at 0.0.0.
sync_package_json_version "packages/google/package.json" "google"
sync_package_json_version "packages/apple/package.json" "apple"

# Function to create symlink
create_symlink() {
    local target="$1"
    local link_path="$2"

    # Remove existing file or symlink
    if [ -e "$target" ] || [ -L "$target" ]; then
        rm "$target"
    fi

    # Create symlink
    ln -s "$link_path" "$target"
    echo "  ✓ $target -> $link_path (symlink)"
}

# Function to copy file
copy_file() {
    local target="$1"

    # Remove existing file or symlink
    if [ -e "$target" ] || [ -L "$target" ]; then
        rm "$target"
    fi

    # Copy file
    cp "openiap-versions.json" "$target"
    echo "  ✓ $target (copied)"
}

# Docs needs real file for Vercel deployment
copy_file "packages/docs/openiap-versions.json"

# Docs cannot import files outside packages/docs on Vercel, so it reads a
# generated copy of the package and SDK versions.
node scripts/verify-docs-version-metadata.mjs --write
echo "  ✓ packages/docs/src/generated/version-metadata.json"

# Native packages can use symlinks
create_symlink "packages/apple/Sources/openiap-versions.json" "../../../openiap-versions.json"

# Compile-time constants for Swift. The JSON above stays the SSOT, but SwiftPM
# copies a resource symlink verbatim and it dangles inside the built bundle, so
# reading it at runtime works in no distribution channel.
generate_apple_version_source() {
    local target="packages/apple/Sources/OpenIapGeneratedVersion.swift"
    python3 - "$target" <<'PYGEN'
import json
import sys

with open("openiap-versions.json", encoding="utf-8") as file:
    versions = json.load(file)

lines = [
    "// Generated by scripts/sync-versions.sh from openiap-versions.json.",
    "// Do not edit.",
    "",
    "enum OpenIapGeneratedVersion {",
]
for key in ("clientProtocol", "apple", "google"):
    value = versions[key]
    lines.append(f'    static let {key} = "{value}"')
lines.append("}")

with open(sys.argv[1], "w", encoding="utf-8") as file:
    file.write("\n".join(lines) + "\n")
PYGEN
    echo "  ✓ $target (generated)"
}

generate_apple_version_source
create_symlink "packages/google/openiap-versions.json" "../../openiap-versions.json"

# Libraries use symlinks to root openiap-versions.json
echo ""
echo "📦 Syncing to libraries..."
create_symlink "libraries/react-native-iap/openiap-versions.json" "../../openiap-versions.json"
create_symlink "libraries/expo-iap/openiap-versions.json" "../../openiap-versions.json"
create_symlink "libraries/flutter_inapp_purchase/openiap-versions.json" "../../openiap-versions.json"
create_symlink "libraries/godot-iap/openiap-versions.json" "../../openiap-versions.json"
create_symlink "libraries/kmp-iap/openiap-versions.json" "../../openiap-versions.json"
create_symlink "libraries/maui-iap/openiap-versions.json" "../../openiap-versions.json"

sync_maui_android_versions() {
    local google_build="packages/google/openiap/build.gradle.kts"
    local maui_props="libraries/maui-iap/src/Directory.Build.props"
    local maui_store_props="libraries/maui-iap/src/OpenIap.Maui/buildTransitive/OpenIap.Maui.props"
    local maui_gradle_props="libraries/maui-iap/android/gradle.properties"

    if [ ! -f "$google_build" ] || [ ! -f "$maui_props" ] || [ ! -f "$maui_store_props" ] || [ ! -f "$maui_gradle_props" ]; then
        echo "  ! Skipping MAUI Android version sync (required files missing)"
        return
    fi

    local play_billing_version
    local amazon_appstore_sdk_version
    local horizon_billing_compatibility_version
    local horizon_platform_kotlin_version
    local gson_version
    play_billing_version=$(python3 - "$google_build" <<'PY'
import re
import sys

text = open(sys.argv[1], encoding="utf-8").read()
match = re.search(r'val\s+playBillingVersion\s*=\s*"([^"]+)"', text)
if not match:
    raise SystemExit("missing playBillingVersion")
print(match.group(1))
PY
)
    amazon_appstore_sdk_version=$(python3 - "$google_build" <<'PY'
import re
import sys

text = open(sys.argv[1], encoding="utf-8").read()
match = re.search(r'com\.amazon\.device:amazon-appstore-sdk:([^"$]+)', text)
if not match:
    raise SystemExit("missing amazon appstore sdk version")
print(match.group(1))
PY
)
    horizon_billing_compatibility_version=$(python3 - "$google_build" <<'PY'
import re
import sys

text = open(sys.argv[1], encoding="utf-8").read()
match = re.search(r'val\s+horizonBillingCompatibilityVersion\s*=\s*"([^"]+)"', text)
if not match:
    raise SystemExit("missing horizonBillingCompatibilityVersion")
print(match.group(1))
PY
)
    horizon_platform_kotlin_version=$(python3 - "$google_build" <<'PY'
import re
import sys

text = open(sys.argv[1], encoding="utf-8").read()
match = re.search(r'val\s+horizonPlatformKotlinVersion\s*=\s*"([^"]+)"', text)
if not match:
    raise SystemExit("missing horizonPlatformKotlinVersion")
print(match.group(1))
PY
)
    gson_version=$(python3 - "$google_build" <<'PY'
import re
import sys

text = open(sys.argv[1], encoding="utf-8").read()
match = re.search(r'com\.google\.code\.gson:gson:([^"$]+)', text)
if not match:
    raise SystemExit("missing gson version")
print(match.group(1))
PY
)
    python3 - "$maui_props" "$maui_store_props" "$play_billing_version" "$amazon_appstore_sdk_version" "$horizon_billing_compatibility_version" "$horizon_platform_kotlin_version" "$gson_version" <<'PY'
import re
import sys

path, store_path, play_billing, amazon_appstore_sdk, horizon_billing_compatibility, horizon_platform_kotlin, gson = sys.argv[1:]
google_build = open("packages/google/openiap/build.gradle.kts", encoding="utf-8").read()
def play_dependency_version(name):
    match = re.search(fr'val\s+{name}\s*=\s*"([^"]+)"', google_build)
    if not match:
        raise SystemExit(f"missing {name}")
    return match.group(1)
play_integrity = play_dependency_version("playIntegrityVersion")
play_core_common = play_dependency_version("playCoreCommonVersion")
import json
core_version = json.load(open("openiap-versions.json", encoding="utf-8"))["google"]
text = open(path, encoding="utf-8").read()
preserved_property_names = [
    "MauiPlayServicesBaseVersion",
    "MauiPlayServicesBasementVersion",
    "MauiPlayServicesLocationVersion",
    "MauiPlayServicesTasksVersion",
    "MauiDataTransportVersion",
    "MauiGoogleGsonNuGetVersion",
    "MauiAndroidXActivityVersion",
    "MauiAndroidXCollectionVersion",
    "MauiComposeAnnotationVersion",
    "MauiAndroidXWindowVersion",
    "MauiAndroidXFragmentVersion",
    "MauiAndroidXFragmentKtxVersion",
    "MauiAndroidXLifecycleVersion",
    "MauiAndroidXSavedStateVersion",
    "MauiKotlinStdLibVersion",
    "MauiKotlinCoroutinesVersion",
    "MauiHorizonSerializationNuGetVersion",
]
preserved = {}
for name in preserved_property_names:
    match = re.search(fr"<{name}>([^<]+)</{name}>", text)
    if not match:
        raise SystemExit(f"missing {name}")
    preserved[name] = match.group(1)

content = f"""<Project>
  <Import Project="..\\Directory.Build.props" />
  <!-- Generated by scripts/sync-versions.sh. Gson follows packages/google/openiap/build.gradle.kts. -->
  <PropertyGroup>
    <MauiHorizonSerializationNuGetVersion>{preserved["MauiHorizonSerializationNuGetVersion"]}</MauiHorizonSerializationNuGetVersion>
    <MauiGsonVersion>{gson}</MauiGsonVersion>
    <MauiPlayServicesBaseVersion>{preserved["MauiPlayServicesBaseVersion"]}</MauiPlayServicesBaseVersion>
    <MauiPlayServicesBasementVersion>{preserved["MauiPlayServicesBasementVersion"]}</MauiPlayServicesBasementVersion>
    <MauiPlayServicesLocationVersion>{preserved["MauiPlayServicesLocationVersion"]}</MauiPlayServicesLocationVersion>
    <MauiPlayServicesTasksVersion>{preserved["MauiPlayServicesTasksVersion"]}</MauiPlayServicesTasksVersion>
    <MauiDataTransportVersion>{preserved["MauiDataTransportVersion"]}</MauiDataTransportVersion>
    <MauiGoogleGsonNuGetVersion>{preserved["MauiGoogleGsonNuGetVersion"]}</MauiGoogleGsonNuGetVersion>
    <MauiAndroidXActivityVersion>{preserved["MauiAndroidXActivityVersion"]}</MauiAndroidXActivityVersion>
    <MauiAndroidXCollectionVersion>{preserved["MauiAndroidXCollectionVersion"]}</MauiAndroidXCollectionVersion>
    <MauiComposeAnnotationVersion>{preserved["MauiComposeAnnotationVersion"]}</MauiComposeAnnotationVersion>
    <MauiAndroidXWindowVersion>{preserved["MauiAndroidXWindowVersion"]}</MauiAndroidXWindowVersion>
    <MauiAndroidXFragmentVersion>{preserved["MauiAndroidXFragmentVersion"]}</MauiAndroidXFragmentVersion>
    <MauiAndroidXFragmentKtxVersion>{preserved["MauiAndroidXFragmentKtxVersion"]}</MauiAndroidXFragmentKtxVersion>
    <MauiAndroidXLifecycleVersion>{preserved["MauiAndroidXLifecycleVersion"]}</MauiAndroidXLifecycleVersion>
    <MauiAndroidXSavedStateVersion>{preserved["MauiAndroidXSavedStateVersion"]}</MauiAndroidXSavedStateVersion>
    <MauiKotlinStdLibVersion>{preserved["MauiKotlinStdLibVersion"]}</MauiKotlinStdLibVersion>
    <MauiKotlinCoroutinesVersion>{preserved["MauiKotlinCoroutinesVersion"]}</MauiKotlinCoroutinesVersion>
  </PropertyGroup>
</Project>
"""
open(path, "w", encoding="utf-8").write(content)

# The app build reads these from the package, so they live beside its targets.
store_content = f"""<Project>
  <!-- Generated by scripts/sync-versions.sh from native package and dependency metadata. -->
  <PropertyGroup>
    <_OpenIapMauiPropsImported>true</_OpenIapMauiPropsImported>
    <MauiOpenIapCoreVersion>{core_version}</MauiOpenIapCoreVersion>
    <MauiPlayBillingVersion>{play_billing}</MauiPlayBillingVersion>
    <MauiPlayIntegrityVersion>{play_integrity}</MauiPlayIntegrityVersion>
    <MauiPlayCoreCommonVersion>{play_core_common}</MauiPlayCoreCommonVersion>
    <MauiAmazonAppstoreSdkVersion>{amazon_appstore_sdk}</MauiAmazonAppstoreSdkVersion>
    <MauiHorizonBillingCompatibilityVersion>{horizon_billing_compatibility}</MauiHorizonBillingCompatibilityVersion>
    <MauiHorizonPlatformKotlinVersion>{horizon_platform_kotlin}</MauiHorizonPlatformKotlinVersion>
  </PropertyGroup>
</Project>
"""
open(store_path, "w", encoding="utf-8").write(store_content)
PY

    python3 - "$maui_gradle_props" "$gson_version" <<'PY'
import re
import sys

path, gson = sys.argv[1:]
text = open(path, encoding="utf-8").read()
if re.search(r'^mauiGsonVersion=', text, flags=re.MULTILINE):
    text = re.sub(r'^mauiGsonVersion=.*$', f'mauiGsonVersion={gson}', text, flags=re.MULTILINE)
else:
    if not text.endswith('\n'):
        text += '\n'
    text += f'mauiGsonVersion={gson}\n'
open(path, "w", encoding="utf-8").write(text)
PY
    echo "  ✓ libraries/maui-iap Android dependency versions"
}

echo ""
echo "📦 Syncing MAUI Android dependency versions..."
sync_maui_android_versions

echo ""
echo "📦 Syncing Godot Android dependency versions..."
./libraries/godot-iap/scripts/sync-versions.sh

# Delegate generated source distribution to the GQL package. It owns every
# source/target mapping and required per-platform post-processing.
echo ""
echo "📦 Syncing generated sources through specs/client..."
node specs/client/scripts/sync-to-platforms.mjs

echo "✅ Version files and generated sources synced successfully"
