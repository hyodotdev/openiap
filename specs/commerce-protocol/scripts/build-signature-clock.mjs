import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

export function signatureClockOperator(spec, tolerance) {
  const section = spec.split(/^#### 9\.4\.2[ \t]/m)[1]?.split(/^#### /m)[0];
  const rule = section?.match(
    /^[ \t]*1\.[ \t]+Reject when[ \t]+`\|now[ \t]*-[ \t]*timestamp\|[ \t]*(>=|>)[ \t]*(\d+)`[ \t]+seconds\b/m,
  );
  if (!rule) {
    throw new Error(
      "SPEC.md §9.4.2 rule 1 must state the timestamp rejection formula.",
    );
  }
  if (
    !Number.isSafeInteger(tolerance) ||
    tolerance <= 0 ||
    Number(rule[2]) !== tolerance
  ) {
    throw new Error(
      `SPEC.md §9.4.2 declares ${rule[2]} seconds, but the signature vector tolerance is ${tolerance}.`,
    );
  }
  return rule[1];
}

function main() {
  const spec = readFileSync(new URL("../SPEC.md", import.meta.url), "utf8");
  const { toleranceSeconds: tolerance } = JSON.parse(
    readFileSync(
      new URL("../vectors/signatures.json", import.meta.url),
      "utf8",
    ),
  );
  const operator = signatureClockOperator(spec, tolerance);
  const cases = [0, tolerance, -tolerance, tolerance + 1, -tolerance - 1].map(
    (skew) => ({
      skew,
      accepted:
        operator === ">"
          ? Math.abs(skew) <= tolerance
          : Math.abs(skew) < tolerance,
    }),
  );
  const output = new URL(
    "../conformance/generated-signature-clock.mjs",
    import.meta.url,
  );
  const source = `// Generated by scripts/build-signature-clock.mjs from SPEC.md §9.4.2. Do not edit.
export const signatureClock = ${JSON.stringify({ operator, cases }, null, 2)};
`;
  if (process.argv.includes("--check")) {
    if (source !== readFileSync(output, "utf8")) {
      throw new Error(
        "Signature clock cases are out of date. Run bun run build in specs/commerce-protocol.",
      );
    }
    console.log("signature clock cases are current");
  } else {
    writeFileSync(output, source);
  }
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  main();
}
