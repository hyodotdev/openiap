#!/usr/bin/env node
/**
 * Emits the behavior ids into Kotlin and Swift so the native conformance
 * suites assert against the same versioned spec as the TypeScript ones.
 *
 * Run with --check to fail instead of writing (used by the parity audit).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  CAPABILITY_MATRIX,
  CAPABILITY_STORES,
} from "../../../specs/client/src/capability-matrix.mjs";
import { ANDROID_PROVIDER_PROFILE } from "../src/spec/android-provider-profile.mjs";
import { providerProfile } from "../src/spec/provider-profile.mjs";
import { BEHAVIORS } from "../src/spec/behaviors.mjs";
import { SUITE_VERSION } from "../src/spec/suite-version.mjs";

const defined = new Set(BEHAVIORS.map((behavior) => behavior.id));
const profileIds = ["android", "ios"].flatMap((platform) => {
  const profile = providerProfile(platform);
  return [
    ...profile.mapping,
    ...profile.runtime,
    ...Object.values(profile.capabilities),
  ];
});
const missing = [...new Set(profileIds)].filter((id) => !defined.has(id));
if (missing.length > 0) {
  throw new Error(
    `Provider profile uses undefined behavior ids: ${missing.join(", ")}`,
  );
}

const ROOT = new URL("../../../", import.meta.url);

const TARGETS = {
  spec: {
    path: "packages/conformance/src/spec/generated-spec.mjs",
    render: () => {
      const clientProtocolVersion = JSON.parse(
        readFileSync(
          fileURLToPath(new URL("openiap-versions.json", ROOT)),
          "utf8",
        ),
      ).clientProtocol;
      return `// Generated by packages/conformance/scripts/generate-behavior-ids.mjs
// Do not edit. Copied from specs/client so the published package is
// self-contained; specs/client remains the source of truth.

export const CLIENT_PROTOCOL_VERSION = ${JSON.stringify(clientProtocolVersion)};

export const CAPABILITY_STORES = Object.freeze(${JSON.stringify(CAPABILITY_STORES)});

export const CAPABILITY_MATRIX = Object.freeze(${JSON.stringify(
        Object.fromEntries(
          Object.entries(CAPABILITY_MATRIX).map(([behavior, entry]) => [
            behavior,
            entry.stores,
          ]),
        ),
        null,
        2,
      )});

/** @returns {'required' | 'optional' | 'unsupported'} */
export function capabilityLevel(behavior, store) {
  const entry = CAPABILITY_MATRIX[behavior];
  if (!entry) throw new Error(\`Unknown capability behavior: \${behavior}\`);
  const level = entry[store];
  if (!level) throw new Error(\`Capability \${behavior} has no entry for store \${store}\`);
  return level;
}
`;
    },
  },
  kotlin: {
    path: "packages/conformance/android/src/main/kotlin/dev/hyo/openiap/conformance/ConformanceBehaviors.kt",
    render: () => {
      const constants = [
        ...new Set([
          ...BEHAVIORS.map((behavior) => behavior.id),
          ...ANDROID_PROVIDER_PROFILE.runtime,
        ]),
      ]
        .map((id) => `    const val ${symbol(id)} = "${id}"`)
        .join("\n");
      const capabilityRows = [
        "pendingPurchases",
        "subscriptionBillingIssue",
        "offerCodeRedemption",
      ]
        .map((behavior) => {
          const stores = ["Google", "Horizon", "Amazon"]
            .map(
              (store) =>
                `"${store}" to "${CAPABILITY_MATRIX[behavior].stores[store]}"`,
            )
            .join(", ");
          return `        "${behavior}" to mapOf(${stores}),`;
        })
        .join("\n");

      return `package dev.hyo.openiap.conformance

// Generated by packages/conformance/scripts/generate-behavior-ids.mjs
// Do not edit. Behavior ids are the versioned public contract; see
// packages/conformance/src/spec/behaviors.mjs.

object ConformanceBehaviors {
    const val SUITE_VERSION = "${SUITE_VERSION}"
    const val CLIENT_PROTOCOL_VERSION = "${JSON.parse(readFileSync(new URL("specs/client/package.json", ROOT), "utf8")).version}"
    val ANDROID_MAPPING_BEHAVIORS = setOf(${ANDROID_PROVIDER_PROFILE.mapping.map(JSON.stringify).join(", ")})
    val ANDROID_PROVIDER_BEHAVIORS = setOf(${ANDROID_PROVIDER_PROFILE.runtime.map(JSON.stringify).join(", ")})
    val PROVIDER_CAPABILITY_BEHAVIORS = mapOf(${Object.entries(
      ANDROID_PROVIDER_PROFILE.capabilities,
    )
      .map(
        ([key, value]) => `${JSON.stringify(key)} to ${JSON.stringify(value)}`,
      )
      .join(", ")})

${constants}

    /** Capability level per store, from specs/client/src/capability-matrix.mjs. */
    val CAPABILITY_MATRIX: Map<String, Map<String, String>> = mapOf(
${capabilityRows}
    )
}
`;
    },
  },
  swift: {
    path: "packages/apple/Tests/OpenIapTests/ConformanceBehaviors.swift",
    render: () => {
      const constants = BEHAVIORS.map(
        (behavior) => `    static let ${camel(behavior.id)} = "${behavior.id}"`,
      ).join("\n");
      return `// Generated by packages/conformance/scripts/generate-behavior-ids.mjs
// Do not edit. Behavior ids are the versioned public contract; see
// packages/conformance/src/spec/behaviors.mjs.

enum ConformanceBehaviors {
    static let suiteVersion = "${SUITE_VERSION}"

${constants}
}
`;
    },
  },
  swiftProvider: {
    path: "packages/conformance/apple/Sources/ProviderBehaviors.swift",
    render: () => {
      const profile = providerProfile("ios");
      return `// Generated by packages/conformance/scripts/generate-behavior-ids.mjs. Do not edit.
public enum ProviderBehaviors {
    public static let suiteVersion = "${SUITE_VERSION}"
    public static let clientProtocolVersion = "${JSON.parse(readFileSync(new URL("specs/client/package.json", ROOT), "utf8")).version}"
    public static let mapping = ${JSON.stringify(profile.mapping)}
    public static let runtime = ${JSON.stringify(profile.runtime)}
    public static let capabilities: [String: String] = [${Object.entries(
      profile.capabilities,
    )
      .map(([key, value]) => `${JSON.stringify(key)}: ${JSON.stringify(value)}`)
      .join(", ")}]
    public static let officialCapabilities = ${JSON.stringify(Object.keys(profile.capabilities).filter((id) => CAPABILITY_MATRIX[id].stores.Apple !== "unsupported"))}
}
`;
    },
  },
};

function symbol(id) {
  return id.replace(/[.-]/g, "_").toUpperCase();
}

function camel(id) {
  const parts = id.replace(/\./g, "-").split("-");
  return (
    parts[0] +
    parts
      .slice(1)
      .map((part) => part[0].toUpperCase() + part.slice(1))
      .join("")
  );
}

const check = process.argv.includes("--check");
const drift = [];

for (const [name, target] of Object.entries(TARGETS)) {
  const absolute = fileURLToPath(new URL(target.path, ROOT));
  const expected = target.render();
  let actual = null;
  try {
    actual = readFileSync(absolute, "utf8");
  } catch {
    actual = null;
  }

  if (actual === expected) continue;

  if (check) {
    drift.push(`${target.path} is out of date (${name})`);
    continue;
  }
  writeFileSync(absolute, expected);
  console.log(`wrote ${target.path}`);
}

if (drift.length > 0) {
  console.error("Conformance behavior id drift:");
  for (const item of drift) console.error(`- ${item}`);
  console.error("Run: bun run --cwd packages/conformance generate:ids");
  process.exit(1);
}

if (check) console.log("Conformance behavior ids are in sync.");
